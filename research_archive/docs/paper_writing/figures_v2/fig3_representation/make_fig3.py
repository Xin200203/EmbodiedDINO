#!/usr/bin/env python3
"""
Fig. 3 -- representation diagnostics that localise the gain before temporal
association.  Panel (a) serves R2 (cross-frame stability), panel (b) serves R1
(within-frame proposal quality).

Reads the numbers directly from the archived experiment record and emits a
standalone TikZ document, so (i) the figure cannot drift from the evidence and
(ii) it uses the paper's own font.  Nothing is hand-transcribed, and there are
no third-party Python dependencies.

Fixes relative to the previous placeholder figure:
  1. Axis was in raw fractions (0-0.075) while the text says "3.3 points".
     Now x100 and labelled in points.
  2. Cross-frame R@1's CI crosses zero but was drawn identically to the two
     significant rows, so the figure appeared to contradict the text. Now
     hollow/grey and marked n.s.
  3. The proposal panel showed only the top-5 budget -- the one budget where all
     four metrics are significant. All budgets are now shown, disclosing the
     decay instead of hiding it.
  4. Sized to \\columnwidth so no scaling occurs and label sizes land at nominal pt.

Usage:  python3 make_fig3.py && latexmk -pdf representation.tex
"""

import json
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[4]
SRC = (
    REPO
    / "docs/experiment_records/20260720_seed_sweep_and_experiment_audit"
    / "artifacts/host76_representation_subset50/analysis/representation_summary.json"
)
OUT = pathlib.Path(__file__).with_name("representation.tex")

OURS, HOST = "embodieddino", "host"

A_METRICS = [  # panel (a) -- R2, top row last so it draws bottom-up
    ("cosine_margin", r"cosine margin"),
    ("retrieval_map", r"cross-frame mAP"),
    ("retrieval_r1", r"cross-frame R@1"),
]
B_METRICS = [  # panel (b) -- R1
    ("recall_iou_0.75", r"recall @ IoU 0.75"),
    ("recall_iou_0.50", r"recall @ IoU 0.50"),
    ("recall_iou_0.25", r"recall @ IoU 0.25"),
    ("mean_best_iou", r"mean best IoU"),
]

# ------------------------------------------------------------------ geometry
W_LBL = 2.60     # cm reserved for row labels
X0, X1 = 2.66, 7.50   # plot area in cm
DMIN, DMAX = -3.0, 8.0    # data range in points
TICKS = [-2, 0, 2, 4, 6, 8]

YA = [5.86, 5.36, 4.86]                 # panel (a) rows
YB = [3.46, 2.76, 2.06, 1.36]           # panel (b) rows
Y_AXIS = 0.92
MARKERS = ["*", "square*", "triangle*"]  # one per budget, small->large K
MSIZE = [1.55, 1.25, 1.35]

data = json.loads(SRC.read_text())


def rows(block, metric):
    return [
        r for r in data["paired_scene_deltas"][block]
        if r["metric"] == metric and r["baseline"] == HOST and r["comparison"] == OURS
    ]


def sig(r):
    return r["ci95_low"] > 0 or r["ci95_high"] < 0


def px(v):
    v = max(DMIN, min(DMAX, v))
    return X0 + (v - DMIN) / (DMAX - DMIN) * (X1 - X0)


L = []
w = L.append

w(r"% GENERATED by make_fig3.py -- do not edit by hand; edit the script.")
w(r"\documentclass[10pt,border=2pt]{standalone}")
w(r"\usepackage{times}\usepackage{amsmath}\usepackage{tikz}")
w(r"\usetikzlibrary{arrows.meta,plotmarks}")
w(r"\definecolor{sigc}{RGB}{47,92,158}")
w(r"\definecolor{nsc}{RGB}{154,154,154}")
w(r"\begin{document}")
w(r"\begin{tikzpicture}[x=1cm,y=1cm,font=\scriptsize,"
  r"lbl/.style={font=\scriptsize,inner sep=1pt}]")

# grid + zero line spanning both panels
for t in TICKS:
    c = "black" if t == 0 else "black!12"
    lw = ".65pt" if t == 0 else ".4pt"
    w(rf"\draw[{c},line width={lw}] ({px(t):.3f},{Y_AXIS:.2f}) -- ({px(t):.3f},6.22);")
    w(rf"\node[lbl,anchor=north] at ({px(t):.3f},{Y_AXIS - 0.06:.2f}) {{{t}}};")
w(rf"\draw[black,line width=.6pt] ({X0:.3f},{Y_AXIS:.2f}) -- ({X1:.3f},{Y_AXIS:.2f});")


def emit(r, y, marker, ms, dy=0.115):
    c = "sigc" if sig(r) else "nsc"
    lo, hi, m = 100 * r["ci95_low"], 100 * r["ci95_high"], 100 * r["mean_delta"]
    w(rf"\draw[{c},line width=.85pt] ({px(lo):.3f},{y:.3f}) -- ({px(hi):.3f},{y:.3f});")
    for x in (lo, hi):
        w(rf"\draw[{c},line width=.85pt] ({px(x):.3f},{y - dy:.3f}) -- ({px(x):.3f},{y + dy:.3f});")
    fill = c if sig(r) else "white"
    w(rf"\draw[{c},line width=.7pt,mark={marker},mark size={ms:.2f}pt,"
      rf"mark options={{fill={fill},draw={c}}}] plot coordinates {{({px(m):.3f},{y:.3f})}};")


# ---- panel (a)
n_a = rows("representation", A_METRICS[0][0])[0]["scenes"]
w(rf"\node[lbl,anchor=west] at (0.02,6.42) "
  rf"{{\bfseries (a) R2 $\cdot$ cross-frame stability\ \normalfont ({n_a} paired scenes)}};")
for (metric, label), y in zip(A_METRICS, YA):
    r = rows("representation", metric)[0]
    w(rf"\node[lbl,anchor=east] at ({W_LBL:.2f},{y:.3f}) {{{label}}};")
    emit(r, y, "*", 1.65)
    if not sig(r):
        w(rf"\node[lbl,anchor=west,text=nsc] at ({px(100 * r['ci95_high']) + 0.08:.3f},{y:.3f}) {{n.s.}};")

# ---- panel (b)
budgets = sorted({r["topk"] for r in data["paired_scene_deltas"]["proposal"] if "topk" in r})
offs = [0.20 * (k - (len(budgets) - 1) / 2) for k in range(len(budgets))]
n_b = rows("proposal", B_METRICS[0][0])[0]["scenes"]
w(rf"\node[lbl,anchor=west] at (0.02,4.04) "
  rf"{{\bfseries (b) R1 $\cdot$ proposal quality, pre-association\ \normalfont ({n_b} paired scenes)}};")
for (metric, label), y in zip(B_METRICS, YB):
    recs = {r["topk"]: r for r in rows("proposal", metric) if "topk" in r}
    w(rf"\node[lbl,anchor=east] at ({W_LBL:.2f},{y:.3f}) {{{label}}};")
    for bud, off, mk, ms in zip(budgets, offs, MARKERS, MSIZE):
        if bud in recs:
            emit(recs[bud], y - off, mk, ms, dy=0.075)

# ---- legend + axis label
lx = X0 + 0.16
for i, (bud, mk, ms) in enumerate(zip(budgets, MARKERS, MSIZE)):
    x = lx + i * 1.28
    w(rf"\draw[sigc,line width=.7pt,mark={mk},mark size={ms:.2f}pt,"
      rf"mark options={{fill=sigc,draw=sigc}}] plot coordinates {{({x:.2f},0.30)}};")
    w(rf"\node[lbl,anchor=west] at ({x + 0.10:.2f},0.30) {{top-{bud}}};")
w(rf"\node[lbl,anchor=east,align=right] at ({W_LBL:.2f},{Y_AXIS - 0.34:.2f}) "
  rf"{{paired-scene difference\\EmbodiedDINO $-$ host (points)}};")

w(r"\end{tikzpicture}")
w(r"\end{document}")

OUT.write_text("\n".join(L) + "\n")
print(f"wrote {OUT.name}  (source: {SRC.relative_to(REPO)})")
print(f"proposal budgets found: {budgets}\n")
print("rows used (points):")
for blk, ms in (("representation", A_METRICS), ("proposal", B_METRICS)):
    for metric, label in ms:
        for r in rows(blk, metric):
            k = f" top-{r['topk']}" if "topk" in r else ""
            print(
                f"  {label:24s}{k:8s} mean={100*r['mean_delta']:+6.3f} "
                f"CI[{100*r['ci95_low']:+6.3f},{100*r['ci95_high']:+6.3f}] "
                f"{'SIG' if sig(r) else ' - '} "
                f"median={100*r['median_delta']:+6.3f} pos={r['positive_scene_fraction']:.2f}"
            )
